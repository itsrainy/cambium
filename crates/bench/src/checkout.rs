//! Mirrors, worktrees, and the generated per-repo configuration.
//!
//! Layout under `$CAMBIUM_SUBJECTS_DIR` (default `~/.cache/cambium/subjects`):
//!
//! ```text
//! <id>.git/              bare mirror, fetched once and updated on demand
//! <id>/                  worktree, checked out at whatever commit a step needs
//! store/<id>/            the benchmark lineage's baseline store (dir backend)
//! output/<id>[-<ver>]/   per-repo (and per Bazel version) --output_base
//! repository_cache/      shared --repository_cache: external fetches once per machine
//! disk_cache/            shared --disk_cache
//! bazelrc                the rc file every benchmark Bazel invocation loads
//! ```
//!
//! Every Bazel invocation the suite makes passes `--output_base` (so parallel
//! benchmark runs on one machine do not fight over a server) and loads the
//! shared rc file for `--repository_cache` and `--disk_cache`. Both travel as
//! startup flags in the generated `cambium.toml`, which the config hash
//! excludes, so the lineage is the same on every machine.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context as _, Result};
use cambium_diff::Repo;
use cambium_engine::{Config, Engine};

use crate::manifest::RepoEntry;
use crate::subject::Subject;

/// The environment variable `--subjects-dir` falls back to. Read by the
/// binary (clap's `env`), never here.
pub const SUBJECTS_DIR_ENV: &str = "CAMBIUM_SUBJECTS_DIR";

#[derive(Clone, Debug)]
pub struct SubjectsDir {
    root: PathBuf,
}

impl SubjectsDir {
    /// `~/.cache/cambium/subjects`: where the mirrors go when nothing says
    /// otherwise.
    pub fn default_root() -> PathBuf {
        crate::util::cache_dir("subjects")
    }

    /// A relative `root` is made absolute against the working directory now:
    /// the paths built from it land in a subject's config, where a relative
    /// store path is read from the subject's workspace and startup flags from
    /// wherever Bazel runs, so one relative root would name three places.
    pub fn new(root: PathBuf) -> Self {
        let root = std::path::absolute(&root).unwrap_or(root);
        Self { root }
    }

    pub fn root(&self) -> &Path {
        &self.root
    }

    /// The bare mirror `entry` clones into.
    pub fn mirror(&self, entry: &RepoEntry) -> PathBuf {
        self.mirror_by_id(&entry.id)
    }

    pub fn mirror_by_id(&self, id: &str) -> PathBuf {
        self.root.join(format!("{id}.git"))
    }

    pub fn worktree(&self, id: &str) -> PathBuf {
        self.root.join(id)
    }

    pub fn store(&self, id: &str) -> PathBuf {
        self.root.join("store").join(id)
    }

    pub fn output_base(&self, id: &str, bazel_version: Option<&str>) -> PathBuf {
        self.root
            .join("output")
            .join(crate::util::versioned_stem(id, bazel_version))
    }

    pub fn repository_cache(&self) -> PathBuf {
        self.root.join("repository_cache")
    }

    pub fn disk_cache(&self) -> PathBuf {
        self.root.join("disk_cache")
    }

    pub fn bazelrc(&self) -> PathBuf {
        self.root.join("bazelrc")
    }

    /// Writes the shared rc file. Idempotent.
    pub fn write_bazelrc(&self) -> Result<PathBuf> {
        std::fs::create_dir_all(&self.root)?;
        std::fs::create_dir_all(self.repository_cache())?;
        std::fs::create_dir_all(self.disk_cache())?;
        let path = self.bazelrc();
        let contents = format!(
            "# Generated by `cambium-bench`. Shared by every subject.\n\
             common --repository_cache={}\n\
             common --disk_cache={}\n\
             # Loading only; never let a benchmark query start fetching toolchains it\n\
             # does not need for analysis.\n\
             common --noshow_progress\n\
             # Bazel rewrites MODULE.bazel.lock on load when the lockfile is\n\
             # stale, which dirties the worktree and makes the next checkout\n\
             # refuse to move. The suite never needs the lockfile.\n\
             common --lockfile_mode=off\n",
            self.repository_cache().display(),
            self.disk_cache().display()
        );
        if std::fs::read_to_string(&path).ok().as_deref() != Some(&contents) {
            std::fs::write(&path, contents)?;
        }
        Ok(path)
    }

    /// Mirror plus worktree at `pin`. Resumable: an existing mirror is
    /// fetched, an existing worktree is moved to `pin`.
    pub fn fetch(&self, entry: &RepoEntry) -> Result<Checkout> {
        std::fs::create_dir_all(&self.root)?;
        let mirror = self.mirror(entry);
        if !mirror.join("HEAD").exists() {
            tracing::info!(url = %entry.url, dest = %mirror.display(), "cloning mirror");
            git(
                &self.root,
                &[
                    "clone",
                    "--quiet",
                    "--mirror",
                    &entry.url,
                    &mirror.display().to_string(),
                ],
            )?;
        } else if !has_commit(&mirror, &entry.pin) {
            tracing::info!(dest = %mirror.display(), "updating mirror");
            git(&mirror, &["fetch", "--quiet", "--prune", "origin"])?;
        }
        if !has_commit(&mirror, &entry.pin) {
            // A pin that no ref reaches any more; GitHub still serves it by sha.
            git(&mirror, &["fetch", "--quiet", "origin", &entry.pin])?;
        }
        anyhow::ensure!(
            has_commit(&mirror, &entry.pin),
            "subject {}: pin {} is not in {}",
            entry.id,
            entry.pin,
            entry.url
        );

        let worktree = self.worktree(&entry.id);
        if !worktree.join(".git").exists() {
            tracing::info!(dest = %worktree.display(), "adding worktree");
            git(
                &mirror,
                &[
                    "worktree",
                    "add",
                    "--quiet",
                    "--detach",
                    &worktree.display().to_string(),
                    &entry.pin,
                ],
            )?;
        }
        let co = Checkout::open(self, entry)?;
        co.checkout(&entry.pin)?;
        Ok(co)
    }

    /// The generated `cambium.toml` for `entry`: defaults plus the manifest's
    /// invalidators, the subject's store, and the startup flags that pin a run to
    /// its own output base. Needs no checkout, so the state file can learn
    /// which cambium it belongs to before the first fetch.
    pub fn config_for(&self, entry: &RepoEntry, bazel_version: Option<&str>) -> Config {
        let mut cfg = Config::default();
        let (paths, globs) = entry.invalidator_rules();
        cfg.invalidators.paths.extend(paths);
        cfg.invalidators.globs.extend(globs);
        cfg.bazel.binary = entry.bazel.clone();
        cfg.bazel.extra_query_flags = entry.extra_query_flags.clone();
        cfg.bazel.startup_flags = vec![
            format!(
                "--output_base={}",
                self.output_base(&entry.id, bazel_version).display()
            ),
            format!("--bazelrc={}", self.bazelrc().display()),
        ];
        cfg.bazel
            .startup_flags
            .extend(entry.extra_startup_flags.iter().cloned());
        cfg.baseline.store = cambium_engine::config::StoreConfig::Dir {
            path: self.store(&entry.id),
        };
        // A history range is 300 commits; a comparison change set's base must be able
        // to find the nearest applied index without a cold build. This is the
        // *manifest's* window, never a run's `--commits`: the walk length is part of
        // the config hash, so shortening it for a quick run would mint a fresh
        // lineage and cold-build the very change sets a short run exists to
        // make cheap. A quick range is a slice of the full one, so a bound
        // that covers the full range covers it too.
        cfg.baseline.max_ancestor_walk = entry.history_window.max(20);
        cfg.baseline.publish_partial = entry.publish_partial.clone();
        cfg
    }

    /// An existing checkout, without touching the network. Prefer
    /// [`open_or_fetch`](Self::open_or_fetch), which knows a synthetic
    /// subject can be produced on the spot.
    pub fn open(&self, entry: &RepoEntry) -> Result<Checkout> {
        Checkout::open(self, entry)
    }

    /// An existing checkout, fetching first if `subject` is synthetic.
    ///
    /// Emitting and cloning a synthetic subject touches no network and is
    /// idempotent, so a workload can run one without a separate `subjects
    /// fetch` step first — which is what CI does. A real subject still needs
    /// that step: [`fetch`](Self::fetch) clones from `entry.url`, which may
    /// cost gigabytes or need credentials, and no workload should start that
    /// by surprise.
    pub fn open_or_fetch(&self, subject: &Subject, entry: &RepoEntry) -> Result<Checkout> {
        if subject.is_synthetic() {
            return self.fetch(entry);
        }
        self.open(entry)
    }
}

/// A subject's worktree.
#[derive(Clone, Debug)]
pub struct Checkout {
    pub id: String,
    pub dir: PathBuf,
    pub mirror: PathBuf,
    pub repo: Repo,
    subjects: SubjectsDir,
}

impl Checkout {
    fn open(subjects: &SubjectsDir, entry: &RepoEntry) -> Result<Self> {
        let dir = subjects.worktree(&entry.id);
        anyhow::ensure!(
            dir.join(".git").exists(),
            // Only a real subject reaches this: `open_or_fetch` emits and
            // clones a synthetic one instead of asking for it. So the id here
            // is also the name a person types, and the suggestion is runnable.
            "no checkout of {} at {}; run `cambium-bench subjects fetch {}`",
            entry.id,
            dir.display(),
            entry.id
        );
        Ok(Self {
            id: entry.id.clone(),
            dir: dir.clone(),
            mirror: subjects.mirror(entry),
            repo: Repo::new(dir),
            subjects: subjects.clone(),
        })
    }

    pub fn head(&self) -> Result<String> {
        Ok(self.repo.rev_parse("HEAD")?)
    }

    /// Moves the worktree to `rev`. Untracked files (the generated
    /// `cambium.toml`) survive. Tracked files are forced: nothing in this
    /// worktree is ever edited on purpose, but Bazel may rewrite a lockfile
    /// and a case-insensitive filesystem can show two same-named files as a
    /// deletion, and neither is worth stopping a 300-commit history over.
    pub fn checkout(&self, rev: &str) -> Result<()> {
        if self.head().ok().as_deref() == Some(rev) {
            return Ok(());
        }
        git(
            &self.dir,
            &["checkout", "--quiet", "--force", "--detach", rev],
        )?;
        Ok(())
    }

    /// The generated `cambium.toml` for this repo: defaults plus the
    /// manifest's invalidators, the subject's store, and the startup flags that
    /// pin this run to its own output base. Written into the worktree (and
    /// excluded from `git status`), never committed upstream.
    pub fn config_for(&self, entry: &RepoEntry, bazel_version: Option<&str>) -> Config {
        self.subjects.config_for(entry, bazel_version)
    }

    pub fn write_config(&self, entry: &RepoEntry, bazel_version: Option<&str>) -> Result<PathBuf> {
        self.subjects.write_bazelrc()?;
        let cfg = self.config_for(entry, bazel_version);
        let path = self.dir.join(cambium_engine::config::CONFIG_FILE);
        std::fs::write(&path, cfg.to_toml())?;
        exclude_from_git(&self.dir, cambium_engine::config::CONFIG_FILE)?;
        Ok(path)
    }

    /// An engine over this checkout, under the requested Bazel version (a
    /// bazelisk `USE_BAZEL_VERSION` override; `None` honours `.bazelversion`).
    pub fn engine(&self, entry: &RepoEntry, bazel_version: Option<&str>) -> Result<Engine> {
        let cfg_path = self.write_config(entry, bazel_version)?;
        let mut engine = Engine::open(&self.dir, Some(&cfg_path), Some(&entry.bazel))
            .with_context(|| format!("opening {}", self.dir.display()))?;
        let env = bazelisk_env(&self.dir, bazel_version);
        if !env.is_empty() {
            let bazel = engine.bazel().clone().with_env(env);
            engine = engine.with_bazel(bazel);
        }
        Ok(engine)
    }
}

/// Where bazelisk downloads Bazel from when nothing redirects it.
pub const BAZEL_RELEASES_URL: &str = "https://github.com/bazelbuild/bazel/releases/download";

/// The bazelisk environment every Bazel invocation over `worktree` carries:
/// the requested `USE_BAZEL_VERSION`, if any, and whatever it takes to keep
/// the repository's own `.bazeliskrc` from routing the suite through the
/// Aspect CLI.
///
/// sourcegraph/sourcegraph's `.bazeliskrc` pins `USE_BAZEL_VERSION=aspect/…`
/// with `BAZELISK_BASE_URL` at the aspect-cli releases, so `bazelisk` there
/// *is* the Aspect CLI, a wrapper that adds its own behaviour in front of the
/// Bazel named by `.bazelversion`. One of those behaviours failed every
/// bazel-diff change set on the first published run: bazel-diff hands the
/// query expression over as `--query_file`, and `aspect query` with no
/// positional expression does not pass the flag through but opens its
/// interactive preset picker ("Select a preset query: why / deps / …"),
/// which reads a nulled stdin, gets EOF, and fails the query with the literal
/// `Error: failed to run 'aspect query': ^D`. `CI=1` does not skip that
/// picker, and it cannot be disabled from outside.
///
/// The comparison wants every tool on the same plain Bazel anyway, so when
/// the rc routes to the Aspect CLI this names the Bazel it would have run
/// (`.bazelversion`, unless the run asked for one) and points bazelisk back
/// at the official releases. bazelisk consults the environment before
/// `.bazeliskrc`, so the two variables win in every workspace of the run —
/// the subject's checkout, the tools' base worktree, Tango's scratch
/// checkouts — without touching a tracked file.
pub fn bazelisk_env(worktree: &Path, bazel_version: Option<&str>) -> Vec<(String, String)> {
    let requested = bazel_version.filter(|v| !v.is_empty()).map(str::to_string);
    let mut env = Vec::new();
    if bazeliskrc_routes_to_aspect(worktree) {
        let version = requested.clone().or_else(|| {
            std::fs::read_to_string(worktree.join(".bazelversion"))
                .ok()
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty())
        });
        let version = version.unwrap_or_else(|| {
            tracing::warn!(
                worktree = %worktree.display(),
                ".bazeliskrc routes to the Aspect CLI and there is no .bazelversion to name \
                 the Bazel underneath; running the latest release instead"
            );
            "latest".to_string()
        });
        tracing::info!(
            worktree = %worktree.display(),
            %version,
            ".bazeliskrc routes bazelisk to the Aspect CLI; running plain Bazel instead"
        );
        env.push(("USE_BAZEL_VERSION".to_string(), version));
        env.push((
            "BAZELISK_BASE_URL".to_string(),
            BAZEL_RELEASES_URL.to_string(),
        ));
    } else if let Some(v) = requested {
        env.push(("USE_BAZEL_VERSION".to_string(), v));
    }
    env
}

/// Whether `<worktree>/.bazeliskrc` makes `bazelisk` run the Aspect CLI: a
/// `USE_BAZEL_VERSION=aspect/…` pin, or a `BAZELISK_BASE_URL` at the
/// aspect-cli releases.
fn bazeliskrc_routes_to_aspect(worktree: &Path) -> bool {
    let Ok(rc) = std::fs::read_to_string(worktree.join(".bazeliskrc")) else {
        return false;
    };
    rc.lines()
        .map(str::trim)
        .filter(|l| !l.starts_with('#'))
        .filter_map(|l| l.split_once('='))
        .any(|(k, v)| match k.trim() {
            "USE_BAZEL_VERSION" => v.trim().starts_with("aspect/"),
            "BAZELISK_BASE_URL" => v.contains("aspect-build/aspect-cli"),
            _ => false,
        })
}

fn has_commit(repo: &Path, sha: &str) -> bool {
    Command::new("git")
        .current_dir(repo)
        .args(["cat-file", "-e", &format!("{sha}^{{commit}}")])
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

fn exclude_from_git(worktree: &Path, name: &str) -> Result<()> {
    let out = Command::new("git")
        .current_dir(worktree)
        .args(["rev-parse", "--git-path", "info/exclude"])
        .output()?;
    if !out.status.success() {
        return Ok(());
    }
    let rel = String::from_utf8_lossy(&out.stdout).trim().to_string();
    let path = if Path::new(&rel).is_absolute() {
        PathBuf::from(rel)
    } else {
        worktree.join(rel)
    };
    let existing = std::fs::read_to_string(&path).unwrap_or_default();
    if !existing.lines().any(|l| l.trim() == name) {
        if let Some(p) = path.parent() {
            std::fs::create_dir_all(p)?;
        }
        std::fs::write(&path, format!("{existing}{name}\n"))?;
    }
    Ok(())
}

pub fn git(dir: &Path, args: &[&str]) -> Result<String> {
    let out = Command::new("git")
        .current_dir(dir)
        .args(args)
        .output()
        .with_context(|| format!("running git {args:?} in {}", dir.display()))?;
    anyhow::ensure!(
        out.status.success(),
        "git {} in {} failed: {}",
        args.join(" "),
        dir.display(),
        String::from_utf8_lossy(&out.stderr).trim()
    );
    Ok(String::from_utf8_lossy(&out.stdout).to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(range: usize) -> RepoEntry {
        RepoEntry {
            id: "r".into(),
            url: "u".into(),
            pin: "0".repeat(40),
            history_window: range,
            bazel: "bazelisk".into(),
            bazel_version: None,
            extra_query_flags: Vec::new(),
            extra_startup_flags: Vec::new(),
            publish_partial: Default::default(),
            invalidators: Vec::new(),
            skip: false,
            notes: String::new(),
        }
    }

    fn checkout() -> Checkout {
        Checkout {
            id: "r".into(),
            dir: PathBuf::from("/tmp/wt"),
            mirror: PathBuf::from("/tmp/mirror"),
            repo: Repo::new("/tmp/wt"),
            subjects: SubjectsDir::new(PathBuf::from("/tmp/subjects")),
        }
    }

    #[test]
    fn a_relative_subjects_dir_gives_a_subject_an_absolute_store() {
        let subjects = SubjectsDir::new(PathBuf::from("subjects"));
        assert!(subjects.root().is_absolute());
        let c = Checkout {
            subjects,
            ..checkout()
        };
        let cambium_engine::config::StoreConfig::Dir { path } =
            c.config_for(&entry(5), None).baseline.store
        else {
            panic!("a subject's store is a directory");
        };
        assert!(path.is_absolute(), "{}", path.display());
    }

    #[test]
    fn a_change_set_base_is_always_inside_the_ancestor_walk() {
        for range in [0, 5, 50, 300] {
            let cfg = checkout().config_for(&entry(range), None);
            // Any `--commits N` a run may ask for is bounded by the
            // manifest's window, so covering the window covers every run.
            assert!(cfg.baseline.max_ancestor_walk >= range, "range {range}");
        }
    }

    #[test]
    fn the_run_size_does_not_reach_the_config_hash() {
        // The walk length is hashed into the store lineage, so it must come
        // from the manifest and never from a run's `--commits`: a short run has
        // to land on the same lineage a full one publishes, or every change
        // set's base cold builds.
        let e = entry(300);
        let cfg = checkout().config_for(&e, None);
        assert_eq!(cfg.baseline.max_ancestor_walk, 300);
        assert_eq!(cfg.hash(), checkout().config_for(&e, None).hash());
    }

    fn worktree_with(files: &[(&str, &str)]) -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        for (name, body) in files {
            std::fs::write(dir.path().join(name), body).unwrap();
        }
        dir
    }

    fn get<'a>(env: &'a [(String, String)], key: &str) -> Option<&'a str> {
        env.iter().find(|(k, _)| k == key).map(|(_, v)| v.as_str())
    }

    #[test]
    fn a_repository_that_routes_bazelisk_to_the_aspect_cli_runs_plain_bazel() {
        // sourcegraph/sourcegraph's actual files: the rc pins the Aspect CLI,
        // .bazelversion names the Bazel it wraps.
        let wt = worktree_with(&[
            (
                ".bazeliskrc",
                "BAZELISK_BASE_URL=https://github.com/aspect-build/aspect-cli/releases/download\n\
                 USE_BAZEL_VERSION=aspect/5.8.19\n",
            ),
            (".bazelversion", "7.2.0\n"),
        ]);
        let env = bazelisk_env(wt.path(), None);
        assert_eq!(get(&env, "USE_BAZEL_VERSION"), Some("7.2.0"));
        assert_eq!(get(&env, "BAZELISK_BASE_URL"), Some(BAZEL_RELEASES_URL));

        // A run that asks for a version gets that version, still off the
        // Aspect releases.
        let env = bazelisk_env(wt.path(), Some("7.4.1"));
        assert_eq!(get(&env, "USE_BAZEL_VERSION"), Some("7.4.1"));
        assert_eq!(get(&env, "BAZELISK_BASE_URL"), Some(BAZEL_RELEASES_URL));
    }

    #[test]
    fn a_repository_on_plain_bazelisk_is_left_alone() {
        let wt = worktree_with(&[(".bazelversion", "7.4.1\n")]);
        assert!(bazelisk_env(wt.path(), None).is_empty());
        assert!(bazelisk_env(wt.path(), Some("")).is_empty());
        let env = bazelisk_env(wt.path(), Some("8.0.0"));
        assert_eq!(
            env,
            vec![("USE_BAZEL_VERSION".to_string(), "8.0.0".to_string())]
        );

        // An rc that does not mention aspect (a mirror, say) is not a route
        // to the Aspect CLI either.
        let wt = worktree_with(&[
            (
                ".bazeliskrc",
                "# comment\nBAZELISK_BASE_URL=https://mirror.example/bazel\n",
            ),
            (".bazelversion", "7.4.1\n"),
        ]);
        assert!(bazelisk_env(wt.path(), None).is_empty());
    }
}
